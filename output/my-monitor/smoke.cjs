require('dotenv').config({path:'backend/.env',quiet:true})
const {chromium}=require('/Users/leon/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome 2.app/Contents/MacOS/Google Chrome'})
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 const db=require('../../backend/src/db/connection')
 const session=db.prepare('SELECT token FROM sessions WHERE expires_at>? ORDER BY created_at DESC LIMIT 1').get(Date.now())
 if(!session)throw new Error('No existing authenticated local session for browser smoke test')
 await page.addInitScript(token=>localStorage.setItem('logearn.auth.token',token),session.token)
 await page.goto('http://localhost:5173',{waitUntil:'networkidle'})
 await page.locator('[data-mode="my-monitor"]:not([disabled])').waitFor({timeout:60000})
 await page.click('[data-mode="my-monitor"]')
 await page.locator('.monitor-hero').waitFor({timeout:60000})
 await page.screenshot({path:'output/my-monitor/desktop.png',fullPage:true})
 console.log('desktop:',await page.locator('.monitor-hero').innerText())
 await page.selectOption('[data-monitor-period]','14');await page.locator('.monitor-hero').waitFor({timeout:60000})
 await page.setViewportSize({width:768,height:1024});await page.screenshot({path:'output/my-monitor/tablet.png',fullPage:true})
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)
 await page.click('[data-mode="home"]');await page.locator('.home-monitor').waitFor({timeout:60000})
 await page.click('[data-mode="my-monitor"]');await page.locator('.monitor-hero').waitFor({timeout:60000})
 console.log(JSON.stringify({errors,tabletOverflow:overflow,cards:await page.locator('.my-monitor .home-kpi').count()}))
 await browser.close();db.close();if(errors.length||overflow)process.exitCode=1
})().catch(e=>{console.error(e);process.exit(1)})
