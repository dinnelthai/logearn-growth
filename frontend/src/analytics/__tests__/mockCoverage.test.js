import {it,expect} from 'vitest';
import users from '../../../mock-api/users.json';
import events from '../../../mock-api/events.json';
import trades from '../../../mock-api/trades.json';
import referrals from '../../../mock-api/referrals.json';
import channels from '../../../mock-api/channels.json';
import facts from '../../../mock-api/channel-facts.json';
import manifest from '../../../mock-api/manifest.json';
import lifecycle from '../../../mock-api/lifecycle-rules.json';
import {datasetFromJson} from '../jsonDataset.js';
import {computeSegmentation} from '../segmentation.js';
import {computeChannels} from '../../channels/analytics.js';
import {computeSharing} from '../sharing.js';
const data=datasetFromJson({users,events,trades,referrals,channels,manifest,'channel-facts':facts,'lifecycle-rules':lifecycle}),asOf=data.meta.asOf,endAt=Math.floor((asOf+7*3600000)/86400000)*86400000-7*3600000,startAt=endAt-14*86400000;
it('八种分群都有JSON样例，中文英文未知及绑定均可比较',()=>{const result=computeSegmentation(data.users,{asOf});for(const ids of Object.values(result.segmentUsers))expect(ids.length).toBeGreaterThan(0);for(const lang of ['zh','en',null])expect(data.users.some(u=>u.preferred_language===lang)).toBe(true)});
it('各渠道都有获客、交易事实及成熟D7样本',()=>{const r=computeChannels({facts,rules:channels.rules,users:data.users,trades:data.trades,startAt,endAt,asOf});for(const g of r.groups){expect(g.visits).toBeGreaterThan(0);expect(g.traders).toBeGreaterThan(0)}expect(r.total.eligible).toBeGreaterThan(0);expect(r.total.retained).toBeGreaterThan(0)});
it('三种分享功能都有事件，链接榜有绑定和激活数据',()=>{const s=computeSharing(data.users,data.referrals,{startAt,endAt,asOf});for(const t of s.types){expect(t.clicks).toBeGreaterThan(0);expect(t.shares).toBeGreaterThan(0)}expect(s.links.some(l=>l.active>0)).toBe(true)});
