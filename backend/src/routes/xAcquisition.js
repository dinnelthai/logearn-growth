const express=require('express')
const {service}=require('../services/xAcquisition')
const router=express.Router()
const wrap=fn=>(req,res,next)=>Promise.resolve().then(()=>fn(req,res,String(req.user.user_id))).catch(next)
const kol=()=>require('../services/kolDiscovery').service()
router.get('/kol',wrap((req,res,owner)=>res.json(kol().list(owner,req.query))))
router.get('/kol/candidates',wrap((req,res,owner)=>res.json(kol().candidates(owner))))
router.post('/kol/bootstrap',wrap((req,res,owner)=>res.json(kol().bootstrap(owner))))
router.post('/kol/accounts',wrap((req,res,owner)=>res.status(201).json({account:kol().add(owner,req.body||{})})))
router.get('/kol/accounts/:id',wrap((req,res,owner)=>res.json(kol().detail(owner,req.params.id,req.query.objective||'trial'))))
router.post('/kol/accounts/:id/refresh',wrap((req,res,owner)=>{res.status(202).json({job:kol().enqueue(owner,req.params.id)})}))
router.put('/kol/accounts/:id/review',wrap((req,res,owner)=>{res.json(kol().saveReview(owner,req.params.id,req.body||{}))}))
router.patch('/kol/accounts/:id',wrap((req,res,owner)=>{res.json(kol().saveFollowup(owner,req.params.id,req.body||{}))}))
router.get('/',wrap((req,res,owner)=>res.json({...service().overview(owner),...service().list(owner,req.query)})))
router.post('/setup',wrap((req,res,owner)=>res.json({settings:service().setup(owner)})))
router.put('/settings',wrap((req,res,owner)=>res.json({settings:service().saveSettings(owner,req.body||{})})))
router.post('/rules',wrap((req,res,owner)=>res.status(201).json({rule:service().saveRule(owner,null,req.body||{})})))
router.patch('/rules/:id',wrap((req,res,owner)=>res.json({rule:service().saveRule(owner,req.params.id,req.body||{})})))
router.post('/collect',wrap((req,res,owner)=>res.status(202).json({run:service().enqueue(owner,req.body||{})})))
router.get('/leads/:id',wrap((req,res,owner)=>res.json(service().detail(owner,req.params.id))))
router.patch('/leads/:id',wrap((req,res,owner)=>res.json(service().updateLead(owner,req.params.id,req.body||{}))))
module.exports=router
