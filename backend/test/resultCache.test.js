const {test}=require('node:test'),assert=require('node:assert/strict')
const {cachePut,cacheGet,memoPut,memoGet,memoKey}=require('../src/analytics/resultCache')
test('result cache evicts oldest results at capacity and preserves recent fixed lists',()=>{
 const ids=Array.from({length:201},(_,i)=>cachePut({lists:{users:['user:'+i]}}))
 assert.equal(cacheGet(ids[0]),null)
 assert.deepEqual(cacheGet(ids[1]).lists.users,['user:1'])
 assert.deepEqual(cacheGet(ids[200]).lists.users,['user:200'])
})
test('memo replacement refreshes insertion order and evicted entries require recalculation',()=>{
 const keys=Array.from({length:100},(_,i)=>memoKey(['capacity',i]))
 keys.forEach((key,i)=>memoPut(key,{i}))
 memoPut(keys[0],{i:'updated'})
 memoPut('overflow',{i:100})
 assert.equal(memoGet(keys[1]),null)
 assert.deepEqual(memoGet(keys[0]),{i:'updated'})
 assert.deepEqual(memoGet('overflow'),{i:100})
})
test('cache hits at the exact TTL boundary expire',t=>{
 t.mock.method(Date,'now',()=>1000)
 const id=cachePut({lists:[]}),key=memoKey(['ttl']);memoPut(key,{ok:true})
 t.mock.method(Date,'now',()=>1000+15*60*1000)
 assert.equal(cacheGet(id),null);assert.equal(memoGet(key),null)
})
test('memoized metrics never return an evicted drill result when analysis is rerun',()=>{
 const id=cachePut({lists:{users:['user:fixed']}}),key=memoKey(['evicted-drill'])
 memoPut(key,{drill:{cache_id:id},total:1})
 assert.equal(memoGet(key).drill.cache_id,id)
 for(let i=0;i<200;i++)cachePut({lists:{users:['user:'+i]}})
 assert.equal(cacheGet(id),null)
 assert.equal(memoGet(key),null)
 const replacement=cachePut({lists:{users:['user:new']}})
 memoPut(key,{drill:{cache_id:replacement},total:1})
 assert.equal(memoGet(key).drill.cache_id,replacement)
})
